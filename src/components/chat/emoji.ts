/** 絵文字と、探すための言葉 */
export const EMOJI_LIST = EMOJI_GROUPS.flatMap((g) =>
  g.items.map((item) => {
    const [emoji, ...words] = item.split(" ");
    return { emoji, words: words.join(" ").toLowerCase() };
  }),
);

const RECENT_KEY = "accord:emoji-recent";
/** よく使う絵文字が無いときに出すもの */
const DEFAULT_RECENT = ["👍", "❤️", "😂", "🙏", "🎉", "✅", "👀", "😭"];

/** 最近使った絵文字（新しい順）。このブラウザの中だけに覚える */
export function recentEmoji(): string[] {
  try {
    const list = JSON.parse(localStorage.getItem(RECENT_KEY) ?? "[]");
    if (Array.isArray(list) && list.length) return [...new Set([...list.filter((x) => typeof x === "string"), ...DEFAULT_RECENT])].slice(0, 24);
  } catch {
    // 読めなければ、いつものものを出す
  }
  return DEFAULT_RECENT;
}

export function rememberEmoji(emoji: string) {
  try {
    const list = [emoji, ...recentEmoji().filter((x) => x !== emoji)].slice(0, 24);
    localStorage.setItem(RECENT_KEY, JSON.stringify(list));
  } catch {
    // 覚えられなくても、選んだ絵文字はそのまま使う
  }
}
